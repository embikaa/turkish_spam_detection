def write_top_terms_table(
    texts: List[str],
    labels: np.ndarray,
    tfidf_vectorizer: Any,
    output_dir: str,
    top_n: int = 20,
) -> Optional[str]:
    """Document frequency of the top TF-IDF terms per weak-label class.

    Uses the fitted vectorizer and the same cleaning as training, so the terms
    are exactly the model's TF-IDF vocabulary. Punctuation, emoji and URLs are
    stripped by that cleaning, hence the table reflects lexical content only.
    """
    from preprocessing import clean_texts

    labels = np.asarray(labels).astype(int).ravel()
    if len(texts) != len(labels):
        print("  Term table skipped: texts and labels differ in length.")
        return None

    X = tfidf_vectorizer.transform(clean_texts(list(texts), method="tfidf"))
    X = (X > 0).astype(np.int32).tocsr()
    terms = tfidf_vectorizer.get_feature_names_out()

    masks = {"Spam": labels == 1, "Genuine": labels == 0}
    n_docs = {c: int(mask.sum()) for c, mask in masks.items()}
    df = {c: np.asarray(X[mask].sum(axis=0)).ravel() for c, mask in masks.items()}

    path = os.path.join(output_dir, "6_top_terms_by_class.csv")
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["class", "rank", "term", "docs_in_class",
                         "pct_in_class", "pct_in_other_class"])
        for cls, other in (("Spam", "Genuine"), ("Genuine", "Spam")):
            if n_docs[cls] == 0:
                continue
            for rank, j in enumerate(np.argsort(df[cls])[::-1][:top_n], start=1):
                writer.writerow([
                    cls, rank, terms[j], int(df[cls][j]),
                    round(100 * df[cls][j] / n_docs[cls], 2),
                    round(100 * df[other][j] / max(n_docs[other], 1), 2),
                ])

    print(f"  Term table saved: {path}")
    return path


