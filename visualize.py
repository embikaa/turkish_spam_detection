def plot_system_architecture(output_dir: str) -> None:
    """Flowchart in the order requested by the referee report."""
    steps = [
        "Raw reviews\n+ weak labels",
        "Stratified split\ntrain / val / test",
        "TF-IDF\n(fit on train)",
        "BERT [CLS]\nembeddings",
        "PCA on BERT\n(fit on train)",
        "Concatenate\nTF-IDF + PCA",
        "Z-score scaler\n(fit on train)",
        "Validation set\nnot oversampled",
        "Oversample\ntrain only",
        "Train models\n(early stop on val)",
        "Test evaluation\n(frozen threshold)",
    ]
    per_row = 6
    box_w, box_h, gap_x, gap_y = 2.0, 1.2, 0.6, 1.0
    n_rows = int(np.ceil(len(steps) / per_row))

    fig, ax = plt.subplots(figsize=(16, 2.4 * n_rows))
    ax.set_xlim(0, per_row * (box_w + gap_x))
    ax.set_ylim(0, n_rows * (box_h + gap_y))
    ax.axis("off")

    centers = []
    for i, text in enumerate(steps):
        row, col = divmod(i, per_row)
        x = col * (box_w + gap_x) + gap_x / 2
        y = (n_rows - 1 - row) * (box_h + gap_y) + gap_y / 2
        ax.add_patch(FancyBboxPatch(
            (x, y), box_w, box_h, boxstyle="round,pad=0.08",
            facecolor="white", edgecolor="black", linewidth=1.5,
        ))
        ax.text(x + box_w / 2, y + box_h / 2, text, ha="center", va="center",
                fontsize=10, fontweight="bold")
        centers.append((x, y))

    for i in range(len(centers) - 1):
        (x0, y0), (x1, y1) = centers[i], centers[i + 1]
        if abs(y0 - y1) < 1e-9:
            start, end = (x0 + box_w, y0 + box_h / 2), (x1, y1 + box_h / 2)
        else:
            start, end = (x0 + box_w / 2, y0), (x1 + box_w / 2, y1 + box_h)
        ax.annotate("", xy=end, xytext=start,
                    arrowprops=dict(arrowstyle="->", color="black", lw=1.8))

    save_figure(fig, output_dir, "0_system_architecture")
    print("  System architecture saved.")


def plot_label_distribution(label_stats: Dict, output_dir: str) -> None:
    """Accepts labeling diagnostics or the legacy {'spam','genuine'} dict."""
    if "class_distribution" in label_stats:
        dist = label_stats["class_distribution"]
        spam = _lookup(dist, ("Spam", "spam", 1, "1"))
        genuine = _lookup(dist, ("Genuine", "genuine", 0, "0"))
    else:
        spam, genuine = label_stats.get("spam"), label_stats.get("genuine")

    if spam is None or genuine is None:
        print("  Label distribution skipped: class counts not found in label_stats.")
        return

    spam, genuine = int(spam), int(genuine)
    total = spam + genuine

    fig, ax = plt.subplots(figsize=(6, 6))
    ax.pie(
        [spam, genuine], explode=(0.05, 0),
        labels=[
            f"Spam\n{spam:,} ({100 * spam / total:.2f}%)",
            f"Genuine\n{genuine:,} ({100 * genuine / total:.2f}%)",
        ],
        colors=[COLORS["spam"], COLORS["genuine"]], startangle=90,
        textprops={"fontsize": 12, "fontweight": "bold"},
        wedgeprops={"linewidth": 1, "edgecolor": "black"},
    )
    save_figure(fig, output_dir, "1_label_distribution")
    print("  Label distribution saved.")


def plot_oversampling_effect(
    y_train_orig: np.ndarray,
    y_train_res: np.ndarray,
    output_dir: str,
) -> None:
    """Training split only; validation and test are never resampled."""
    before = np.bincount(np.asarray(y_train_orig).astype(int).ravel(), minlength=2)
    after = np.bincount(np.asarray(y_train_res).astype(int).ravel(), minlength=2)

    fig, axes = plt.subplots(1, 2, figsize=(10, 4), sharey=True)
    for ax, counts, title in zip(
        axes, (before, after),
        ("(a) Training set, before oversampling", "(b) Training set, after oversampling"),
    ):
        bars = ax.bar(["Genuine", "Spam"], counts,
                      color=[COLORS["genuine"], COLORS["spam"]], edgecolor="black")
        ax.set_title(title, fontsize=11)
        ax.grid(axis="y", linestyle="--", alpha=0.7)
        for bar in bars:
            ax.annotate(f"{int(bar.get_height()):,}",
                        (bar.get_x() + bar.get_width() / 2, bar.get_height()),
                        ha="center", va="bottom", xytext=(0, 3),
                        textcoords="offset points", fontsize=10)
    axes[0].set_ylabel("Number of samples")

    save_figure(fig, output_dir, "2_oversampling_effect")
    print("  Oversampling plot saved.")


