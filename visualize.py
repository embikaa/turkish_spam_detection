def setup_style() -> None:
    plt.rcParams.update({
        "figure.facecolor": COLORS["bg"],
        "axes.facecolor": COLORS["bg"],
        "axes.edgecolor": "black",
        "axes.labelcolor": COLORS["text"],
        "text.color": COLORS["text"],
        "xtick.color": COLORS["text"],
        "ytick.color": COLORS["text"],
        "grid.color": COLORS["grid"],
        "font.family": "sans-serif",
        "font.size": 12,
        "pdf.fonttype": 42,
    })


def save_figure(fig: plt.Figure, output_dir: str, stem: str) -> None:
    """Raster for preview, vector PDF for the manuscript."""
    fig.savefig(os.path.join(output_dir, f"{stem}.png"), dpi=300, bbox_inches="tight")
    fig.savefig(os.path.join(output_dir, f"{stem}.pdf"), bbox_inches="tight")
    plt.close(fig)


def clean_old_plots(output_dir: str) -> None:
    """Remove only files produced by this module (current and legacy names)."""
    if not os.path.isdir(output_dir):
        return

    targets = [f"{s}.{ext}" for s in GENERATED_STEMS for ext in ("png", "pdf")]
    targets += list(GENERATED_TABLES) + list(LEGACY_FILES)

    removed = 0
    for name in targets:
        path = os.path.join(output_dir, name)
        if os.path.exists(path):
            try:
                os.remove(path)
                removed += 1
            except OSError:
                pass

    if removed:
        print(f"  Removed {removed} old files generated by visualize.py.")


def _valid_results(results: Dict) -> Dict[str, Dict]:
    return {
        name: m for name, m in (results or {}).items()
        if isinstance(m, dict) and "error" not in m
    }


def rank_results(results: Dict) -> List[Tuple[str, Dict]]:
    """Single ranking rule shared with train.py."""
    def key(item):
        value = item[1].get(RANKING_METRIC)
        return -np.inf if value is None else float(value)

    return sorted(_valid_results(results).items(), key=key, reverse=True)


def _split_suffix(split_label: Optional[str]) -> str:
    return f" ({split_label} set)" if split_label else ""


def _lookup(mapping: Dict, keys: Tuple) -> Optional[int]:
    for k in keys:
        if k in mapping:
            return mapping[k]
    return None


