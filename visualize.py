"""visualize.py — paper figures and tables, all drawn from one results dict.

Referee findings handled in this module:
  * Bulgu 4 / Section 4: every model figure is drawn from the same results dict
    that produces the test table; the split name is printed on the figure and
    the confusion-matrix F1 is cross-checked against the reported F1;
  * Bulgu 5 / 6: the PCA figure states that PCA is applied to BERT only and
    prints the resulting V_hybrid dimension;
  * Bulgu 7: ranking uses train.RANKING_METRIC everywhere and every model,
    Random Forest included, appears in the comparison figure;
  * Bulgu 8: ROC curves for every model, AUC written as a proportion (0.976);
  * Bulgu 9: the impurity-importance figure is labelled as Random Forest MDI,
    so it cannot be confused with the SHAP analysis of the ANN;
  * Fig. 7: word clouds replaced by a quantitative term table;
  * every figure is also written as vector PDF; the flowchart follows the
    order requested in the report.
"""
