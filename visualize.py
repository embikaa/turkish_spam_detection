def plot_tsne_distribution(
    X: np.ndarray,
    y: np.ndarray,
    output_dir: str,
    sample_size: int = 1500,
    seed: int = 42,
    split_label: Optional[str] = None,
) -> None:
    """2-D t-SNE of a seeded sample of non-oversampled data.

    t-SNE preserves local neighbourhoods only; axes carry no meaning, so ticks
    are hidden and the figure must not be read as global class separation.
    """
    y = np.asarray(y).astype(int).ravel()
    rng = np.random.default_rng(seed)

    if len(X) > sample_size:
        idx = rng.choice(len(X), sample_size, replace=False)
        X, y = X[idx], y[idx]

    print(f"  Computing t-SNE on {len(y):,} samples{_split_suffix(split_label)}...")
    emb = TSNE(n_components=2, perplexity=30, init="pca",
               random_state=seed).fit_transform(X)

    fig, ax = plt.subplots(figsize=(7, 6))
    for cls, name, color in ((0, "Genuine", COLORS["genuine"]),
                             (1, "Spam", COLORS["spam"])):
        mask = y == cls
        ax.scatter(emb[mask, 0], emb[mask, 1], s=25, alpha=0.7,
                   c=color, edgecolors="k", linewidths=0.3,
                   label=f"{name} (n={int(mask.sum())})")
    ax.set_xticks([])
    ax.set_yticks([])
    ax.set_xlabel("t-SNE 1")
    ax.set_ylabel("t-SNE 2")
    ax.set_title(f"t-SNE{_split_suffix(split_label)}", fontsize=11)
    ax.legend(loc="best")

    save_figure(fig, output_dir, "7_tsne_plot")
    print("  t-SNE plot saved.")


def plot_pca_variance(
    pca_model: Any, output_dir: str, n_tfidf: Optional[int] = None
) -> None:
    """Cumulative variance of the BERT-only PCA and the V_hybrid size (Bulgu 5/6)."""
    cumulative = np.cumsum(pca_model.explained_variance_ratio_)
    k = int(pca_model.n_components_)
    d_in = int(getattr(pca_model, "n_features_in_", 0))

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.plot(np.arange(1, k + 1), cumulative, color=COLORS["accent"], lw=2,
            label="Cumulative explained variance")
    ax.scatter(k, cumulative[-1], color=COLORS["spam"], s=80, zorder=5,
               label=f"Selected k = {k} ({100 * cumulative[-1]:.1f}%)")
    ax.set_xlabel(f"Number of principal components (BERT [CLS], d = {d_in})")
    ax.set_ylabel("Cumulative explained variance ratio")
    ax.grid(linestyle="--", alpha=0.5)
    ax.legend(loc="lower right")

    note = "PCA input: BERT embeddings only"
    if n_tfidf is not None:
        note += f"\nV_hybrid = {n_tfidf} TF-IDF + {k} PCA = {n_tfidf + k}"
    ax.text(0.02, 0.97, note, transform=ax.transAxes, va="top", fontsize=10,
            bbox=dict(boxstyle="round", facecolor="white", edgecolor="gray"))

    save_figure(fig, output_dir, "8_pca_variance")
    print("  PCA variance plot saved.")


def plot_rf_mdi_importance(
    results: Dict, tfidf_vectorizer: Any, output_dir: str, top_n: int = 15
) -> None:
    """Random Forest impurity importance of TF-IDF terms; not SHAP (Bulgu 9)."""
    rf = _valid_results(results).get("Random Forest", {})
    if "feature_importances" not in rf:
        return

    terms = tfidf_vectorizer.get_feature_names_out()
    imp = np.asarray(rf["feature_importances"], dtype=float)[:len(terms)]
    top = np.argsort(imp)[::-1][:top_n]

    fig, ax = plt.subplots(figsize=(9, 7))
    ax.barh(np.arange(len(top))[::-1], imp[top], color=COLORS["spam"], edgecolor="black")
    ax.set_yticks(np.arange(len(top))[::-1])
    ax.set_yticklabels([terms[i] for i in top])
    ax.set_xlabel("Mean decrease in impurity (Random Forest)")
    ax.set_title("Random Forest MDI importance, TF-IDF terms only (not SHAP)",
                 fontsize=11)
    ax.grid(axis="x", linestyle="--", alpha=0.5)

    save_figure(fig, output_dir, "9_rf_mdi_importance")
    print("  RF MDI importance saved.")


