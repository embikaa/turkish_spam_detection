def plot_best_model_cm(
    results: Dict, output_dir: str, split_label: Optional[str] = None
) -> None:
    ranked = rank_results(results)
    if not ranked or "cm" not in ranked[0][1]:
        return

    name, m = ranked[0]
    cm = np.asarray(m["cm"], dtype=int)

    # Bulgu 4: the F1 implied by the matrix must equal the F1 in the table.
    tn, fp, fn, tp = cm.ravel()
    cm_f1 = 2 * tp / (2 * tp + fp + fn) if (2 * tp + fp + fn) else 0.0
    if "f1" in m and abs(cm_f1 - float(m["f1"])) > 1e-3:
        print(f"  WARNING: F1 from confusion matrix ({cm_f1:.4f}) "
              f"!= reported F1 ({float(m['f1']):.4f}) for {name}.")

    print(f"  Plotting confusion matrix for {name}{_split_suffix(split_label)}...")
    fig, ax = plt.subplots(figsize=(5.5, 4.5))
    sns.heatmap(cm, annot=True, fmt="d", cmap="Blues", cbar=False,
                xticklabels=["Genuine", "Spam"], yticklabels=["Genuine", "Spam"],
                annot_kws={"size": 14}, linewidths=0.5, linecolor="black", ax=ax)
    ax.set_ylabel("True label")
    ax.set_xlabel("Predicted label")
    ax.set_title(
        f"{name}{_split_suffix(split_label)}\n"
        f"macro-F1 = {m.get('macro_f1', float('nan')):.4f} | "
        f"spam F1 = {cm_f1:.4f}",
        fontsize=11,
    )
    save_figure(fig, output_dir, "3_best_model_cm")


def plot_model_comparison(
    results: Dict, output_dir: str, split_label: Optional[str] = None
) -> None:
    """All models, ordered by RANKING_METRIC (Bulgu 7)."""
    ranked = rank_results(results)
    if not ranked:
        return

    names = [n for n, _ in ranked]
    x = np.arange(len(names))
    width = 0.8 / len(COMPARISON_METRICS)
    palette = sns.color_palette("tab10", len(COMPARISON_METRICS))

    fig, ax = plt.subplots(figsize=(max(8, 2.2 * len(names)), 5))
    for i, (key, label) in enumerate(COMPARISON_METRICS):
        values = [float(m.get(key, np.nan)) for _, m in ranked]
        offset = (i - (len(COMPARISON_METRICS) - 1) / 2) * width
        bars = ax.bar(x + offset, values, width, label=label,
                      color=palette[i], edgecolor="black")
        for bar, v in zip(bars, values):
            if np.isfinite(v):
                ax.annotate(f"{v:.3f}", (bar.get_x() + bar.get_width() / 2, v),
                            ha="center", va="bottom", xytext=(0, 2),
                            textcoords="offset points", fontsize=7, rotation=90)

    ax.set_xticks(x)
    ax.set_xticklabels(names)
    ax.set_ylim(0, 1.15)
    ax.set_ylabel("Score")
    ax.set_title(f"Ranked by {RANKING_METRIC}{_split_suffix(split_label)}", fontsize=11)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.1),
              ncol=len(COMPARISON_METRICS), fontsize=9, frameon=False)
    ax.grid(axis="y", linestyle="--", alpha=0.6)

    save_figure(fig, output_dir, "4_model_comparison")
    print("  Model comparison saved.")


def plot_roc_curves(
    results: Dict, output_dir: str, split_label: Optional[str] = None
) -> None:
    """ROC for every model; AUC as a proportion with three decimals (Bulgu 8)."""
    ranked = [(n, m) for n, m in rank_results(results) if "fpr" in m and "tpr" in m]
    if not ranked:
        return

    fig, ax = plt.subplots(figsize=(6.5, 5.5))
    for name, m in ranked:
        ax.plot(m["fpr"], m["tpr"], lw=2,
                label=f"{name} (AUC = {float(m.get('auc', np.nan)):.3f})")
    ax.plot([0, 1], [0, 1], color="gray", lw=1, linestyle="--", label="Chance")
    ax.set_xlim(0, 1)
    ax.set_ylim(0, 1.02)
    ax.set_xlabel("False positive rate")
    ax.set_ylabel("True positive rate")
    ax.set_title(f"ROC curves{_split_suffix(split_label)}", fontsize=11)
    ax.legend(loc="lower right", fontsize=9)
    ax.grid(linestyle="--", alpha=0.5)

    save_figure(fig, output_dir, "5_roc_curves")
    print("  ROC curves saved.")


