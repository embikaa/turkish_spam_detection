def create_all_plots(
    results: Dict,
    label_stats: Dict,
    output_dir: str,
    split_label: Optional[str] = None,
    texts: Optional[List[str]] = None,
    labels: Optional[np.ndarray] = None,
    X_embed: Optional[np.ndarray] = None,
    y_embed: Optional[np.ndarray] = None,
    embed_split_label: Optional[str] = None,
    y_train_orig: Optional[np.ndarray] = None,
    y_train_res: Optional[np.ndarray] = None,
    pca_model: Optional[Any] = None,
    tfidf_vectorizer: Optional[Any] = None,
    seed: int = 42,
) -> None:
    setup_style()
    os.makedirs(output_dir, exist_ok=True)

    print("\nGenerating figures and tables...")
    clean_old_plots(output_dir)

    plot_system_architecture(output_dir)

    if label_stats:
        plot_label_distribution(label_stats, output_dir)

    if y_train_orig is not None and y_train_res is not None:
        plot_oversampling_effect(y_train_orig, y_train_res, output_dir)

    if results:
        plot_best_model_cm(results, output_dir, split_label)
        plot_model_comparison(results, output_dir, split_label)
        plot_roc_curves(results, output_dir, split_label)

    if texts is not None and labels is not None and tfidf_vectorizer is not None:
        write_top_terms_table(texts, labels, tfidf_vectorizer, output_dir)

    if X_embed is not None and y_embed is not None:
        plot_tsne_distribution(X_embed, y_embed, output_dir, seed=seed,
                               split_label=embed_split_label)

    if pca_model is not None:
        n_tfidf = (len(tfidf_vectorizer.get_feature_names_out())
                   if tfidf_vectorizer is not None else None)
        plot_pca_variance(pca_model, output_dir, n_tfidf=n_tfidf)

    if results and tfidf_vectorizer is not None:
        plot_rf_mdi_importance(results, tfidf_vectorizer, output_dir)

    print(f"\nAll figures saved to '{output_dir}' (PNG + PDF).")
